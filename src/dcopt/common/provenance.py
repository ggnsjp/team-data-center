"""Where the data is and whether it is the data we think it is.

`data/register.toml` lists every dataset: where it is stored, its terms, how it is made and
processed, what uses it and which tests check it. `data/SHA256SUMS` pins the bytes of every
committed data file, in the format `shasum -a 256 -c` reads, so anyone can verify a clone
without this package.

`stamp()` gives the block an experiment saves next to its results: the git commit, whether
there were uncommitted changes, the fingerprint of the committed data and the package versions.
A result can then be traced to the exact code and data that produced it.

Run    uv run python -m dcopt.common.provenance            check the data against SHA256SUMS
       uv run python -m dcopt.common.provenance --write    re-pin after an intended data change, and
                                                           refresh the lineage diagram in the docs
       uv run python -m dcopt.common.provenance --report   the register as a table, with status
       uv run python -m dcopt.common.provenance --cypher   the register as a lineage graph for Neo4j
       uv run python -m dcopt.common.provenance --mermaid  the same graph as a Mermaid diagram
"""
from __future__ import annotations

import hashlib
import json
import platform
import subprocess
import sys
import tomllib
from datetime import UTC, datetime
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REGISTER = ROOT / "data" / "register.toml"
SUMS = ROOT / "data" / "SHA256SUMS"
DOC = ROOT / "docs" / "data-accountability.md"
DOC_MARKERS = ("<!-- lineage:start (generated by --write) -->", "<!-- lineage:end -->")
PACKAGES = ("dcopt", "numpy", "pandas", "highspy", "streamlit")


def register() -> list[dict]:
    with REGISTER.open("rb") as f:
        return tomllib.load(f)["dataset"]


def committed_files(datasets: list[dict] | None = None) -> list[Path]:
    """The files of every storage = "git" dataset, sorted, relative to the repository root."""
    files: set[Path] = set()
    for d in datasets or register():
        if d["storage"] == "git":
            for pattern in d["paths"]:
                files.update(p.relative_to(ROOT) for p in ROOT.glob(pattern) if p.is_file())
    return sorted(files)


def sha256(path: Path) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def read_sums() -> dict[str, str]:
    """data/SHA256SUMS as {path: digest}. Paths are relative to data/, as shasum -c expects there."""
    sums = {}
    for line in SUMS.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            digest, name = line.split(maxsplit=1)
            sums[name.lstrip("*")] = digest
    return sums


def write_sums() -> int:
    files = committed_files()
    lines = [f"{sha256(p)}  {p.relative_to('data').as_posix()}" for p in files]
    SUMS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines)


def verify() -> list[str]:
    """Problems found, empty when every committed data file matches SHA256SUMS exactly."""
    sums = read_sums()
    actual = {p.relative_to("data").as_posix(): sha256(p) for p in committed_files()}
    problems = [f"changed: data/{n}" for n in sorted(actual) if n in sums and sums[n] != actual[n]]
    problems += [f"not pinned: data/{n}" for n in sorted(set(actual) - set(sums))]
    problems += [f"missing: data/{n}" for n in sorted(set(sums) - set(actual))]
    return problems


def fingerprint() -> str:
    """One digest for all committed data: the SHA-256 of SHA256SUMS (short form)."""
    return hashlib.sha256(SUMS.read_bytes()).hexdigest()[:16]


def _git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def stamp(**extra) -> dict:
    """The provenance block for a result file."""
    versions = {}
    for name in PACKAGES:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            pass
    return {"created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
            "git_commit": _git("rev-parse", "HEAD"),
            "uncommitted_changes": bool(_git("status", "--porcelain", "--untracked-files=no")),
            "data_fingerprint": fingerprint(),
            "data_problems": verify(),
            "python": platform.python_version(),
            "packages": versions, **extra}


def report() -> str:
    problems = verify()
    rows = ["| Dataset | Stored | Where | Terms | Made by |", "|---|---|---|---|---|"]
    for d in register():
        rows.append(f"| {d['title']} | {d['storage']} | {', '.join(f'`{p}`' for p in d['paths'])} "
                    f"| {d['licence']} | `{d['made_by']}` |")
    n = len(committed_files())
    status = "all match" if not problems else f"{len(problems)} problem(s): " + "; ".join(problems)
    return "\n".join(rows) + f"\n\nCommitted data files: {n}, {status}. Fingerprint {fingerprint()}."


# ------------------------------------------------------------------------------------ lineage graph
def lineage() -> tuple[dict[str, dict], list[tuple[str, str, str]]]:
    """The register as a graph: nodes {key: {label, ...props}} and edges (from, type, to).

    (:Source)-[:FEEDS]->(:Dataset)<-[:MAKES]-(:Code), (:Dataset)-[:STORED_IN]->(:Location),
    (:Dataset)-[:USED_BY]->(:Code|:App|:Experiment), (:Test)-[:CHECKS]->(:Dataset),
    (:Dataset)-[:UNDER]->(:Licence)."""
    nodes: dict[str, dict] = {}
    edges: list[tuple[str, str, str]] = []

    def file_node(path: str) -> str:
        label = ("Test" if path.startswith("tests/") else "App" if path.startswith("app/")
                 else "Experiment" if path.startswith("experiments/") else "Code")
        nodes.setdefault(path, {"label": label, "path": path})
        return path

    for d in register():
        key = d["id"]
        nodes[key] = {"label": "Dataset", "id": key, "title": d["title"], "storage": d["storage"],
                      "made_by": d["made_by"], "processing": d["processing"], "refresh": d["refresh"]}
        lic = "licence:" + d["terms"]
        nodes.setdefault(lic, {"label": "Licence", "name": d["terms"]})
        edges.append((key, "UNDER", lic))
        for url in d["sources"]:
            nodes.setdefault(url, {"label": "Source", "url": url})
            edges.append((url, "FEEDS", key))
        for path in d["paths"]:
            loc = "loc:" + path
            nodes.setdefault(loc, {"label": "Location", "path": path, "in_git": d["storage"] != "local"})
            edges.append((key, "STORED_IN", loc))
        edges += [(file_node(c), "MAKES", key) for c in d.get("code", [])]
        edges += [(key, "USED_BY", file_node(u)) for u in d["used_by"]]
        edges += [(file_node(t), "CHECKS", key) for t in d["checks"]]
        if d["storage"] == "git":
            nodes.setdefault("sums", {"label": "Checksums", "path": "data/SHA256SUMS", "fingerprint": fingerprint()})
            edges.append(("sums", "PINS", key))
    return nodes, edges


def cypher() -> str:
    """Idempotent Cypher (MERGE) that loads the lineage graph into Neo4j. Paste into the Neo4j
    Browser, or: cypher-shell -f lineage.cypher. Re-running updates the graph in place."""
    nodes, edges = lineage()
    q = json.dumps
    lines = ["// generated by: uv run python -m dcopt.common.provenance --cypher"]
    for key, props in nodes.items():
        props = dict(props)
        label = props.pop("label")
        sets = ", ".join(f"n.{k} = {q(v, ensure_ascii=False)}" for k, v in props.items())
        lines.append(f"MERGE (n:{label} {{key: {q(key, ensure_ascii=False)}}}) SET {sets};")
    for a, rel, b in edges:
        lines.append(f"MATCH (a {{key: {q(a, ensure_ascii=False)}}}), (b {{key: {q(b, ensure_ascii=False)}}}) "
                     f"MERGE (a)-[:{rel}]->(b);")
    return "\n".join(lines) + "\n"


def mermaid() -> str:
    """The lineage as a Mermaid flowchart (GitHub renders it): sources, datasets, code and tests."""
    nodes, edges = lineage()
    ids = {k: f"n{i}" for i, k in enumerate(nodes)}
    shape = {"Dataset": '[("{}")]', "Source": '>"{}"]', "Test": '{{"{}"}}', "Licence": '(["{}"])', "Checksums": '[/"{}"/]'}
    out = ["flowchart LR"]
    for k, n in nodes.items():
        if n["label"] == "Location":
            continue
        text = (n.get("title") or n.get("name") or n.get("path") or n.get("url", k)).replace('"', "'")
        if n["label"] == "Source":
            text = text.split("//")[-1]
            text = text if len(text) <= 46 else text[:45] + "…"
        out.append(f"  {ids[k]}" + shape.get(n["label"], '["{}"]').format(text))
    out += [f"  {ids[a]} -->|{r.lower()}| {ids[b]}" for a, r, b in edges if not b.startswith("loc:")]
    return "\n".join(out) + "\n"


def doc_diagram() -> str:
    """The block between DOC_MARKERS in the accountability page."""
    return f"{DOC_MARKERS[0]}\n```mermaid\n{mermaid()}```\n{DOC_MARKERS[1]}"


def write_doc() -> None:
    text = DOC.read_text(encoding="utf-8")
    head, rest = text.split(DOC_MARKERS[0], 1)
    tail = rest.split(DOC_MARKERS[1], 1)[1]
    DOC.write_text(head + doc_diagram() + tail, encoding="utf-8")


def main(argv: list[str]) -> int:
    if "--write" in argv:
        n = write_sums()
        write_doc()
        print(f"pinned {n} files in {SUMS.relative_to(ROOT)}; fingerprint {fingerprint()}; "
              f"lineage diagram refreshed in {DOC.relative_to(ROOT)}")
        return 0
    if "--cypher" in argv:
        print(cypher(), end="")
        return 0
    if "--mermaid" in argv:
        print(mermaid(), end="")
        return 0
    if "--report" in argv:
        print(report())
        return 0
    problems = verify()
    for p in problems:
        print(p)
    print(f"{len(committed_files())} committed data files, "
          f"{'all match' if not problems else f'{len(problems)} problem(s)'}; fingerprint {fingerprint()}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
